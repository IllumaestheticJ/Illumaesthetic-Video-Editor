"""overlay_v3.json: one label per teardown step (reviewer rule: label each step; names only, no numbers), timed from
timeline_v3.json. Text comes from the scan/part file names and what the final frames show. POS can override x/y per shot
after looking at the assembled frames (labels sit in clear black; 'shadow' keeps them legible on full-bleed shots)."""
import json, os
D = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
tl = json.load(open(D + "/timeline_v3.json")); bars = tl["bars"]
PLATE = {"s02_under_r", "s03_under_f", "s13_int_console"}   # full-frame scan, no clear black: dark backing plate
LAB = {  # shot: (title, sub, first half-beat, x, y, align, shadow)
    "s02_under_r": ("UNDERBODY PLASTICS", "UNDERTRAYS · ARCH LINERS", 1, 0.08, 0.84, "left", True),
    "s03_under_f": ("UNDERBODY", "TRANSMISSION · FRONT SUBFRAME", 1, 0.08, 0.84, "left", True),
    "s04_fb_off": ("FRONT BUMPER", "INSIDE + OUTSIDE SCANNED", 2, 0.08, 0.80, "left", False),
    "s05_fb_sub": ("RADAR GRILLE", "COVER + MOUNTING FRAME", 2, 0.08, 0.80, "left", False),
    "s06_fb_beam": ("FRONT BUMPER OFF", "CRASH BEAM · RADIATORS", 1, 0.08, 0.80, "left", False),
    "s07_fb_duct": ("DUCTS REMOVED", "FRONT END · SECOND SCAN", 1, 0.08, 0.80, "left", False),
    "s07b_hood": ("HOOD", "ENGINE BAY", 3, 0.08, 0.84, "left", True),
    "s08_fc_brake": ("FRONT CORNER", "STEERING · WHEEL · BRAKE", 1, 0.08, 0.88, "left", True),
    "s09_fc_strut": ("FRONT SUSPENSION", "STRUT · KNUCKLE · ARMS", 1, 0.08, 0.86, "left", True),
    "s10_fender": ("FENDER SECTION", "UNDER FENDER", 2, 0.08, 0.84, "left", True),
    "s11_skirts": ("SIDE SKIRTS", "LOWER · UPPER · DOOR TRIM", 1, 0.08, 0.09, "left", False),
    "s11b_sill": ("SKIRTS REMOVED", "SILL · CLIP MOUNTS", 1, 0.08, 0.84, "left", True),
    "s12_int_xray": ("INTERIOR", "SEATS · DASH · STEERING WHEEL", 2.5, 0.08, 0.07, "left", False),
    "s13_int_console": ("CENTER CONSOLE", "TUNNEL · WIRING", 1.5, 0.08, 0.88, "left", True),
    "s14_rc": ("REAR SUSPENSION", "BRAKE · FIVE-LINK · SPRING", 1, 0.08, 0.09, "left", False),
    "s15_rb_off": ("REAR BUMPER", "INSIDE + OUTSIDE SCANNED", 2, 0.08, 0.80, "left", False),
    "s16_rb_beam": ("REAR BUMPER OFF", "CRASH BEAM · WIRING · EXHAUST", 1, 0.08, 0.80, "left", False),
    "s16b_lamp_off": ("TAIL LIGHT", "LEFT REAR", 2, 0.08, 0.86, "left", True),
    "s16c_lamp_ex": ("TAIL LIGHT", "LENS · INSERT · HOUSING", 1.5, 0.08, 0.86, "left", False),
}
HB = tl["bar"] / 8 * 30
items = []
for s in tl["shots"]:
    if s["shot"] not in LAB:
        continue
    t, sub, h, x, y, al, sh = LAB[s["shot"]]
    a, b = s["reel_frames"]; f0 = a + int(round(h * HB))
    items.append(dict(kind="label", **{"from": f0}, duration=b - 9 - f0, title=t, sub=sub, x=x, y=y, align=al, shadow=sh, plate=s["shot"] in PLATE))
json.dump(dict(_note="A90 v4 labels - generated by tools/labels_v3.py", width=1080, height=1920, fps=30, durationInFrames=bars[-1],
               accent="#e8ecf2", items=items), open(D + "/overlay_v3.json", "w"), indent=1, ensure_ascii=False)
print(len(items), "labels,", bars[-1], "frames; longest title", max(len(i["title"]) for i in items), "sub", max(len(i["sub"]) for i in items))
