"""Write project_v3.yaml from timeline_v3.json (bar lines measured on the excerpt's kicks). Hard cuts on bar lines.
30 fps shots are native; 15 fps shots are interpolated. ive assemble makes a cut as a 1-frame xfade with a cloned frame,
so the first clip is one frame short (lesson: FG2 / Miata NA) - verified on the delivered file, not here."""
import json, os
D = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
R = "/home/user/media/work/a90/renders_v3/"
tl = json.load(open(D + "/timeline_v3.json"))
L = ["# Toyota A90 Supra v4 - generated by tools/project_v3.py; do not hand-edit (plan: direction_v3.md, shots: tools/plan_v3.py).",
     "# Music: user-supplied track, 24 bars from the song's beginning (0.517 s) (bar 2.6773 s); every cut on a bar line; front bumper off on the A->B entry.",
     "project: a90-supra", "format: reel-9x16",
     "output: {path: /home/user/media/work/out/a90_supra_scan_v4.mp4, width: 1080, height: 1920, fps: 30, crf: 15, preset: slow}",
     "music:", "  path: /home/user/media/a90-supra/music_v3/excerpt_v4.wav", "  start: 0", "  fade_out: 0.05",
     "overlays:", "  - {src: /home/user/media/work/a90/labels_v3.mov, start: 0}",
     "beats: [" + ", ".join(f"{b / 30:.3f}" for b in tl["bars"]) + "]", "timeline:"]
first = True
for s in tl["shots"]:
    n = s["shot"]
    if n == "s12a_shell":
        continue
    a, b = s["reel_frames"]; frames = b - a
    if n == "s19_clean":
        frames = 60
    if not first:
        L.append("  - transition: {type: cut}")
    src = "s12_comp" if n == "s12_int_xray" else n
    L += [f"  - id: {n}", f"    src: {R}{src}", f"    src_fps: {s['fps']}"]
    if s["fps"] == 15:
        L.append("    interpolate: true")
    L.append(f"    dur: {(frames - (1 if first else 0)) / 30:.4f}")
    if n == "s19_clean":
        L.append('    vf: "fade=t=out:st=1.33:d=0.67"')
    if n == "s17_lineup":      # the parked parts touched the left frame edge for a quarter of the shot: 5 % smaller, on black
        L.append('    vf: "scale=1026:1824:flags=lanczos,pad=1080:1920:27:48:black"')
    first = False
L += ["  - transition: {type: cut}", "  - id: logo", "    src: /home/user/media/work/a90/logo_card_v4.mp4", f"    dur: {(tl['bars'][-1] - tl['bars'][-3] - 60) / 30:.4f}"]   # v4: + BD logo (logo_card_v4.sh)
open(D + "/project_v3.yaml", "w").write("\n".join(L) + "\n")
print(D + "/project_v3.yaml")
