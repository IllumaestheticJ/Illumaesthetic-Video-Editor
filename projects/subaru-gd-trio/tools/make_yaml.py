"""Write project.yaml for the GD trio reel from tools/shots_trio.py (15 segments, cuts on kicks) + logo.

    python projects/subaru-gd-trio/tools/make_yaml.py [out_name] [music_start]
"""
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from shots_trio import CUTS, SEG, W

SECTION = {"F1": ("front", "face, whole car"), "F2": ("front", "lamps, grille, scoop"), "R1": ("rear", "wing / tail, whole car"),
           "R2": ("rear", "tail lamps, wing, roof vane"), "T1": ("top", "scoop, wing, vane from above")}
NAME = {"bug": "Bugeye Full Car", "blob": "Blobeye Full Car", "hawk": "Hawkeye Full Car"}
LOGO_FRAMES = 54
out = sys.argv[1] if len(sys.argv) > 1 else "subaru_gd_trio_v1.mp4"
start = float(sys.argv[2]) if len(sys.argv) > 2 else 8.630
L = ["# Subaru Impreza GD trio (bugeye / blobeye / hawkeye): same camera on three registered full-car scans, hard cut on every kick.",
     "# Generated by tools/make_yaml.py from tools/shots_trio.py. Plan: direction.md.",
     "project: subaru-gd-trio", "format: reel-9x16",
     f"output: {{path: {W}/out/{out}, width: 1080, height: 1920, fps: 30, crf: 16, preset: slow}}", "",
     "music:", "  path: /home/user/media/work/music/subaru-gd-trio_rallyhouse.mp3", f"  start: {start}", "  fade_out: 0.3", "",
     "beats: [" + ", ".join(f"{c / 30:.3f}" for c in CUTS[1:]) + "]", "", "timeline:"]
for i, (sid, (_, _, _, frames)) in enumerate(SEG.items()):
    m, car = sid.split("_")
    n = len(glob.glob(f"{W}/renders/final/{sid}/*.png"))
    dur = (frames - (1 if i == 0 else 0)) / 30
    if i:
        L.append(f"  - transition: {{type: cut, note: \"{CUTS[i] / 30:.3f} s\"}}")
    L += [f"  - id: {sid}   # {NAME[car]}, camera move {m}", f"    src: {W}/renders/final/{sid}", f"    section: {SECTION[m][0]}",
          f"    focus: \"{SECTION[m][1]}\"", f"    src_fps: {(n - 1) / (dur + 3 / 30):.4f}   # {n} frames", "    interpolate: true", f"    dur: {dur:.4f}"]
L += [f"  - transition: {{type: cut, note: \"{CUTS[-1] / 30:.3f} s\"}}", "  - id: logo   # 720 px logo on the last kick",
      f"    src: {W}/out/logo_720.mp4", f"    dur: {LOGO_FRAMES / 30:.4f}", "",
      "overlays:", f"  - {{src: {W}/out/hud.mov, start: 0}}   # overlay.json: BUGEYE / BLOBEYE / HAWKEYE under the car in F1", ""]
open("projects/subaru-gd-trio/project.yaml", "w").write("\n".join(L))
print("\n".join(L[-12:]))
