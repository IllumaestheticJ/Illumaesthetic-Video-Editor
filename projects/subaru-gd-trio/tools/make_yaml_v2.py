"""v2: same 15 renders re-timed to the user's track (RALLY HOUSE 002, 122 BPM, bar 1.9672 s, drop at 15.80 s).

    python projects/subaru-gd-trio/tools/make_yaml_v2.py [out_name]

Cuts are measured kick attacks in the track (40-120 Hz envelope, 50 % rise), not a fitted grid: the groove is syncopated.
Each segment keeps its own stretch of the camera move (src_fps = 15 x planned frames / new frames), so the camera still
continues through every car swap.
"""
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from shots_trio import SEG, W
from make_yaml import NAME, SECTION

START = 9.94      # music start (s): just ahead of the bar-line kick at 9.95
# music time of each cut: F1 blob (last kick before the break), F1 hawk (synth accent in the break), then the drop
KICKS = [11.833, 14.033, 15.808, 16.789, 17.773, 18.757, 19.743, 20.724, 21.708, 22.692, 23.678, 24.657, 26.627, 27.611, 28.592]
CUTS = [0] + [round((k - START) * 30) for k in KICKS]
LOGO_FRAMES = 54
if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "subaru_gd_trio_v2.mp4"
    L = ["# Subaru GD trio v2: v1's renders re-timed to the user's track (RALLY HOUSE 002). Generated by tools/make_yaml_v2.py.",
         "project: subaru-gd-trio", "format: reel-9x16",
         f"output: {{path: {W}/out/{out}, width: 1080, height: 1920, fps: 30, crf: 16, preset: slow}}", "",
         "music:", "  path: /home/user/media/work/music/subaru-gd-trio_rallyhouse002.m4a", f"  start: {START}", "  fade_out: 0.6", "",
         "beats: [" + ", ".join(f"{c / 30:.3f}" for c in CUTS[1:]) + "]", "", "timeline:"]
    for i, (sid, (_, _, _, planned)) in enumerate(SEG.items()):
        m, car = sid.split("_")
        n = len(glob.glob(f"{W}/renders/final/{sid}/*.png"))
        frames = CUTS[i + 1] - CUTS[i]
        dur = (frames - (1 if i == 0 else 0)) / 30
        rate = 15 * planned / frames
        if rate > 16:   # a 4-beat hawkeye segment now holds half as long: play its first half at the neighbours' speed
            rate = 13.2
        if i:
            L.append(f"  - transition: {{type: cut, note: \"{CUTS[i] / 30:.3f} s, music {KICKS[i - 1]:.3f} s\"}}")
        L += [f"  - id: {sid}   # {NAME[car]}, camera move {m}", f"    src: {W}/renders/final/{sid}", f"    section: {SECTION[m][0]}",
              f"    focus: \"{SECTION[m][1]}\"", f"    src_fps: {rate:.4f}   # {n} frames, planned {planned} out frames, now {frames}",
              "    interpolate: true", f"    dur: {dur:.4f}"]
    L += [f"  - transition: {{type: cut, note: \"{CUTS[-1] / 30:.3f} s\"}}", "  - id: logo   # 720 px logo on a kick",
          f"    src: {W}/out/logo_720.mp4", f"    dur: {LOGO_FRAMES / 30:.4f}", "",
          "overlays:", f"  - {{src: {W}/out/hud_v2.mov, start: 0}}   # overlay_v2.json: car names under the car in F1", ""]
    open("projects/subaru-gd-trio/project.yaml", "w").write("\n".join(L))
    print(CUTS)
