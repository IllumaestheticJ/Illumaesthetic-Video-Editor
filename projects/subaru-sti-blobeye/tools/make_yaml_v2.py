"""Write project.yaml for v2 from the cut frames in direction.md and the rendered frame counts.

    python projects/subaru-sti-blobeye/tools/make_yaml_v2.py [out_name]

src_fps = (N-1)/(dur + 3 frames) so minterpolate's tail loss never freezes before a cut (v1 lesson).
"""
import glob
import sys

R = "/home/user/media/work/sti/renders/final"
CUTS = [0, 97, 241, 337, 385, 661, 901, 949, 1045, 1178]   # kick attacks measured on the decoded v2 audio (150 BPM, kick every 0.400 s)
SHOTS = [("S1_rear34", f"{R}/s2_rear34", "whole car, rear-left 3/4 orbit, moving from frame 1 (v1 s2 reused)"),
         ("S2_wing", f"{R}/S2_wing", "wing lifts off on bar 3 (4.80), camera tilts down onto the wing-off trunk scan"),
         ("S3_skirt", f"{R}/S3_skirt", "left side skirt drops off over the 'sideskirt removed' sill scan"),
         ("S4_wheel", f"{R}/S4_wheel", "front-left wheel: spokes, caliper, disc"),
         ("S5_hood", f"{R}/S5_hood", "hood + scoop, hood lifts off on bar 9 (12.69), held descent over the engine-bay scan"),
         ("S6_bumper", f"{R}/S6_bumper_m", "HERO: front bumper off, intercooler core on bar 16 (25.32), slide to the piping (labels)"),
         ("S7a_explode", f"{R}/S7a_explode", "exploded state, high left"),
         ("S7b_reassemble", f"{R}/S7b_reassemble", "reassembly, last lock on bar 21 (33.22), fade to black 34.01-34.80")]
TAGS = {"S1_rear34": ("whole", "whole car, wing"), "S2_wing": ("rear", "wing off -> trunk lid / mount pads"),
        "S3_skirt": ("side", "bare left sill"), "S4_wheel": ("wheel", "front-left wheel + caliper"),
        "S5_hood": ("engine", "hood scoop -> engine bay"), "S6_bumper": ("front", "intercooler core + piping"),
        "S7a_explode": ("whole", "all removed parts around the car"), "S7b_reassemble": ("whole", "parts lock home")}
BARS = ["bar 3 (3.217 s shot end)", "", "", "", "", "", "", "bar 22 (34.80)"]

out = sys.argv[1] if len(sys.argv) > 1 else "subaru_sti_blobeye_v2.mp4"
L = ["# Subaru Impreza STI GD 'blobeye' - v2 (direction.md). Scan only; labels only on the bumper-removed hero.",
     "# Generated by tools/make_yaml_v2.py (cut frames on measured kick attacks (decoded audio; the track is 150 BPM, kick every 0.400 s)).",
     "project: subaru-sti-blobeye", "format: reel-9x16",
     f"output: {{path: /home/user/media/work/sti/out/{out}, width: 1080, height: 1920, fps: 30, crf: 16, preset: slow}}", "",
     "music:", "  path: /home/user/media/work/music/subaru-sti-blobeye_track.mp3", "  start: 0", "  fade_out: 0.3", "",
     "beats: [" + ", ".join(f"{c / 30:.3f}" for c in CUTS[1:-1]) + "]", "", "timeline:"]
for i, (sid, src, note) in enumerate(SHOTS):
    n = len(glob.glob(f"{src}/*.png"))
    frames = CUTS[i + 1] - CUTS[i] - (1 if i == 0 else 0)
    dur = frames / 30
    if i:
        L.append(f"  - transition: {{type: cut, note: \"{CUTS[i] / 30:.3f} s\"}}")
    L += [f"  - id: {sid}   # {note}", f"    src: {src}", f"    section: {TAGS[sid][0]}", f"    focus: \"{TAGS[sid][1]}\"", f"    src_fps: {(n - 1) / (dur + 3 / 30):.4f}   # {n} frames", "    interpolate: true",
          f"    dur: {dur:.4f}"]
    if sid == "S7b_reassemble":
        st = 34.0127 - CUTS[i] / 30
        L.append(f"    vf: \"fade=t=out:st={st:.4f}:d={34.80 - 34.0127:.4f}\"   # fade to black 34.01-34.80 (note 7)")
L += ["  - transition: {type: cut, note: \"34.800 s\"}",
      "  - id: logo   # small 280 px logo after 0.4 s black, through the final hit 37.95, fades with the music",
      "    src: /home/user/media/work/sti/out/logo_small.mp4", f"    dur: {(CUTS[-1] - CUTS[-2]) / 30:.4f}", "",
      "overlays:", "  - {src: /home/user/media/work/sti/out/hud_v2.mov, start: 25.0667}   # overlay.json (frame 752; first label enters on the 25.24 s kick): FRONT BUMPER REMOVED / INTERCOOLER PIPING", ""]
open("projects/subaru-sti-blobeye/project.yaml", "w").write("\n".join(L))
print("\n".join(L))
