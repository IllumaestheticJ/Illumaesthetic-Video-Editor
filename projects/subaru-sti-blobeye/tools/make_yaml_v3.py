"""Write project.yaml for v3 (single-scan shots, 1:1 state swaps). Cuts on measured kick attacks (150 BPM, frame 97 + 12k).

    python projects/subaru-sti-blobeye/tools/make_yaml_v3.py [out_name]
"""
import glob
import sys

R = "/home/user/media/work/sti/renders/final"
# (id, src dir, section, focus, note, start frame)
SHOTS = [("O1_open", "O1_open", "whole", "whole car, wing", "Blobeye Full Car: rear-left 3/4 orbit, moving from frame 1", 0),
         ("R_a", "R_a", "rear", "wing", "full car: push in on the wing / trunk", 97),
         ("R_b", "R_b", "rear", "trunk lid without the wing", "STATE SWAP -> 'Rear Wing data' scan (rear captured with the wing off), alone", 157),
         ("wheel", "s3_wheel", "wheel", "front-right wheel + caliper", "full car 2 mm: wheel, caliper, disc", 241),
         ("light", "s4_light", "front", "headlight -> hood scoop", "full car 2 mm: blobeye headlight to the scoop", 289),
         ("H_a", "H_a", "engine", "hood + scoop", "full car: push in over the hood", 337),
         ("E_bay", "E_bay", "engine", "engine bay", "STATE SWAP -> 'GD Scan Engine Bay' scan, alone", 397),
         ("B_a", "B_a", "front", "front bumper", "full car: low push in on the bumper", 565),
         ("B_b", "B_b", "front", "intercooler core", "STATE SWAP -> 'bumper removed' scan, alone (label)", 613),
         ("B_c", "B_c", "front", "intercooler piping", "STATE SWAP -> 'all removed' scan (bumper + hood off), alone (label)", 757),
         ("close", "s1_front34", "whole", "whole car, front", "full car: front-right 3/4 turntable, fade to black", 901)]
END, LOGO = 1045, 1178

out = sys.argv[1] if len(sys.argv) > 1 else "subaru_sti_blobeye_v4.mp4"
L = ["# Subaru Impreza STI GD 'blobeye' - v3 edit (file v4): every shot is ONE scan as captured; removals are 1:1 state swaps.",
     "# Generated by tools/make_yaml_v3.py. Cuts on measured kick attacks (150 BPM, kick every 0.400 s -> frame 97 + 12k).",
     "project: subaru-sti-blobeye", "format: reel-9x16",
     f"output: {{path: /home/user/media/work/sti/out/{out}, width: 1080, height: 1920, fps: 30, crf: 16, preset: slow}}", "",
     "music:", "  path: /home/user/media/work/music/subaru-sti-blobeye_track.mp3", "  start: 0", "  fade_out: 0.3", "",
     "beats: [" + ", ".join(f"{s[5] / 30:.3f}" for s in SHOTS[1:]) + f", {END / 30:.3f}]", "", "timeline:"]
for i, (sid, d, sec, foc, note, st) in enumerate(SHOTS):
    nxt = SHOTS[i + 1][5] if i + 1 < len(SHOTS) else END
    n = len(glob.glob(f"{R}/{d}/*.png"))
    dur = (nxt - st - (1 if i == 0 else 0)) / 30
    if i:
        L.append(f"  - transition: {{type: cut, note: \"{st / 30:.3f} s\"}}")
    L += [f"  - id: {sid}   # {note}", f"    src: {R}/{d}", f"    section: {sec}", f"    focus: \"{foc}\"",
          f"    src_fps: {(n - 1) / (dur + 3 / 30):.4f}   # {n} frames", "    interpolate: true", f"    dur: {dur:.4f}"]
    if sid == "close":
        L.append(f"    vf: \"fade=t=out:st={dur - 0.8:.4f}:d=0.7667\"   # fade to black before the logo")
L += [f"  - transition: {{type: cut, note: \"{END / 30:.3f} s\"}}",
      "  - id: logo   # small 280 px logo after 0.4 s black, through the final hit, fades with the music",
      "    src: /home/user/media/work/sti/out/logo_small.mp4", f"    dur: {(LOGO - END) / 30:.4f}", "",
      "overlays:", f"  - {{src: /home/user/media/work/sti/out/hud_v3.mov, start: {613 / 30:.4f}}}   # overlay.json: labels on the two bumper-off state scans", ""]
open("projects/subaru-sti-blobeye/project.yaml", "w").write("\n".join(L))
print("\n".join(L))
