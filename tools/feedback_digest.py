"""Collect every piece of reviewer/user feedback from every branch into knowledge/feedback/<project>.md.
usage: python tools/feedback_digest.py        (run `git fetch origin` first)
feedback.jsonl files are not markdown, live in 47 project folders and on several session branches that were never
merged; this writes one readable page per project plus the lesson lines that exist only on other branches, so agents
(and the graphify knowledge graph) can see every edit the owner has asked for."""
import json, subprocess, collections, re
from pathlib import Path
def git(*a): return subprocess.run(['git', *a], capture_output=True, text=True).stdout
branches = [b.strip() for b in git('branch', '-r').splitlines() if 'HEAD' not in b]
fb = collections.defaultdict(dict); src = collections.defaultdict(set)
for br in branches:
    for path in git('ls-tree', '-r', '--name-only', br, '--', 'projects').splitlines():
        if not path.endswith('/feedback.jsonl'): continue
        proj = path.split('/')[1]
        for line in git('show', f'{br}:{path}').splitlines():
            try: r = json.loads(line)
            except Exception: continue
            key = (r.get('ts'), (r.get('note') or '').strip())
            fb[proj].setdefault(key, r); src[(proj, key)].add(br.replace('origin/', ''))
out = Path('knowledge/feedback'); out.mkdir(parents=True, exist_ok=True)
for old in out.glob('*.md'): old.unlink()
cats = collections.Counter(); total = 0; index = []
for proj in sorted(fb):
    rows = sorted(fb[proj].values(), key=lambda r: r.get('ts') or ''); total += len(rows)
    L = [f'# Feedback: {proj}', '', f'{len(rows)} notes, oldest first. Source: `projects/{proj}/feedback.jsonl` on every branch. Generated by `tools/feedback_digest.py`; do not edit by hand.', '']
    for r in rows:
        key = (r.get('ts'), (r.get('note') or '').strip()); cats[r.get('category') or 'uncategorised'] += 1
        at = f" @ {r['at']}s" if r.get('at') not in (None, '') else ''; rule = ' **[standing rule]**' if r.get('promoted') else ''
        only = sorted(src[(proj, key)]); where = '' if 'claude/video-editing-scan-data-8o0m8g' in only or 'claude/kind-keller-ya29zp' in only else f"  _(only on {', '.join(only)})_"
        L.append(f"- **[{r.get('category') or 'note'}]**{at} {key[1]}{rule}  _({(r.get('ts') or '')[:10]}, {r.get('by') or 'reviewer'})_{where}")
    (out / f'{proj}.md').write_text('\n'.join(L) + '\n'); index.append((proj, len(rows), sum(1 for r in rows if r.get('promoted'))))
# lesson lines that exist only on other branches
have = set(l.strip() for l in Path('knowledge/lessons.md').read_text().splitlines()); extra = collections.OrderedDict()
for br in branches:
    for l in git('show', f'{br}:knowledge/lessons.md').splitlines():
        s = l.strip()
        if s.startswith('- ') and len(s) > 40 and s not in have: extra.setdefault(s, br.replace('origin/', ''))
if extra:
    (out / '_lessons-from-other-branches.md').write_text('# Lessons that exist only on unmerged branches\n\nNot yet in `knowledge/lessons.md`. Generated by `tools/feedback_digest.py`.\n\n' + '\n'.join(f'{l}  _(branch {b})_' for l, b in extra.items()) + '\n')
I = ['# All reviewer and owner feedback, by project', '', f'{total} notes across {len(fb)} projects and {len(branches)} branches. Standing rules are also in `knowledge/lessons.md`.', '',
     'By category: ' + ', '.join(f'{k} {v}' for k, v in cats.most_common()), '', '| project | notes | standing rules |', '|---|---|---|'] + [f'| [{p}]({p}.md) | {n} | {k} |' for p, n, k in index]
if extra: I += ['', f'{len(extra)} lesson lines exist only on unmerged branches: [_lessons-from-other-branches.md](_lessons-from-other-branches.md)']
(out / 'INDEX.md').write_text('\n'.join(I) + '\n'); print(f'{total} notes, {len(fb)} projects, {len(branches)} branches, {len(extra)} unmerged lesson lines'); print(cats.most_common())
